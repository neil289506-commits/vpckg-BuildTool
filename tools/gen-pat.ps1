# 產生不開源的 secret/PatProvider_private.cpp（PAT 以隨機金鑰 XOR 混淆後嵌入）
# 用法:  .\tools\gen-pat.ps1            （互動輸入，不會留在歷史記錄）
#        .\tools\gen-pat.ps1 -Pat github_pat_xxx
param([string]$Pat)

if (-not $Pat) {
    $sec = Read-Host "貼上 PAT" -AsSecureString
    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec)
    try { $Pat = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr) }
    finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
}
$Pat = $Pat.Trim()
if ($Pat.Length -lt 20) { throw "PAT 看起來太短" }

$data = [Text.Encoding]::ASCII.GetBytes($Pat)
$key  = New-Object byte[] 16
$rng  = [Security.Cryptography.RandomNumberGenerator]::Create()
$rng.GetBytes($key)

$enc = New-Object byte[] $data.Length
for ($i = 0; $i -lt $data.Length; $i++) { $enc[$i] = $data[$i] -bxor $key[$i % 16] }

$keyStr  = ($key | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', '
$dataStr = ($enc | ForEach-Object { '0x{0:x2}' -f $_ }) -join ', '
$n = $data.Length

$code = @"
// AUTO-GENERATED by tools/gen-pat.ps1 - DO NOT COMMIT (see .gitignore)
#include "PatProvider.h"
#include <QByteArray>

namespace {
constexpr unsigned char kKey[16] = { $keyStr };
constexpr unsigned char kData[$n] = { $dataStr };
}

QString PatProvider::token()
{
    QByteArray out;
    out.resize($n);
    for (int i = 0; i < $n; ++i)
        out[i] = static_cast<char>(kData[i] ^ kKey[i % 16]);
    return QString::fromLatin1(out);
}
"@

$target = Join-Path (Split-Path $PSScriptRoot -Parent) 'secret\PatProvider_private.cpp'
[IO.File]::WriteAllText($target, $code, (New-Object Text.UTF8Encoding $false))
Write-Host "已產生 $target  (重新執行 CMake configure 後生效)"
